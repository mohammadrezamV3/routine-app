export type CatalogItem = {
  name: string;
  nameEn: string;
  caloriesPer100g: number;
  proteinPer100g: number;
  carbsPer100g: number;
  fatPer100g: number;
  aliases: string[];
};

function parse(block: string): CatalogItem[] {
  const out: CatalogItem[] = [];
  for (const raw of block.split("\n")) {
    const line = raw.trim();
    if (!line) continue;
    const p = line.split("|");
    if (p.length < 6) throw new Error(`foodCatalog: bad line "${line}"`);
    const [name, nameEn, kcal, pr, ca, fa, al] = p;
    out.push({
      name: name.trim(),
      nameEn: nameEn.trim(),
      caloriesPer100g: Number(kcal),
      proteinPer100g: Number(pr),
      carbsPer100g: Number(ca),
      fatPer100g: Number(fa),
      aliases: (al || "").split(";").map((s) => s.trim()).filter(Boolean),
    });
  }
  return out;
}

export const CATALOG_ITEMS: CatalogItem[] = [STAPLES, IRANIAN, FRESH, TREATS, SNACKS, DRINKS, EXTRAS, BRANDS_IR, FASTFOOD2].flatMap(parse);

