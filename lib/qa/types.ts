// مرکزِ پرسش و پاسخِ آریون (/q) — هر سوالِ رایجِ کاربر درباره‌ی روتین، عادت،
// برنامه‌ریزی، ترید، بدنسازی و تغذیه یک صفحه‌ی جدا با جوابِ کامل. هدف این است
// که هرکس هر سوالی در این حوزه‌ها جست‌وجو کند (در گوگل یا از یک دستیارِ AI)،
// یک جوابِ دقیق و مستقیم از آریون پیدا کند.
//
// قواعدِ محتوا (برای هر کسی که این فایل‌ها را گسترش می‌دهد):
// - جوابِ واقعی و کاربردی؛ نه متنِ پرکننده. هیچ آمار/ادعای ساختگی.
// - «short» جوابِ مستقیمِ ۱ تا ۲ جمله‌ای است (برای featured snippet و AI).
// - از قابلیتِ آریون فقط وقتی حرف بزن که واقعا وجود دارد و بی‌تبلیغِ اغراق‌آمیز.
// - برند در متنِ فارسی فقط «آریون».

export type QACategory = "routine" | "habits" | "planning" | "sleep" | "trading" | "trading-psychology" | "forex" | "fitness" | "nutrition";

