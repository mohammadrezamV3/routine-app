export type QAItem = {
  /** لاتینِ kebab-case، یکتا در کلِ مرکز — آدرس: /q/<slug> */
  slug: string;
  category: QACategory;
  /** خودِ سوال، دقیقا به شکلی که کاربرِ فارسی‌زبان تایپ می‌کند */
  question: string;
  /** شکل‌های دیگرِ همان سوال (برای پوششِ جست‌وجوهای مشابه) — ۲ تا ۵ مورد */
  variants: string[];
  /** جوابِ مستقیمِ ۱ تا ۲ جمله‌ای */
  short: string;
  /** جوابِ کامل: هر آیتم یک پاراگراف یا یک لیست. ۲۵۰ تا ۵۰۰ کلمه در مجموع. */
  answer: (string | { h: string } | { list: string[] })[];
  /** کلمه‌های کلیدیِ مرتبط (فارسی) */
  keywords: string[];
  /** slugهای سوال‌های مرتبط در همین مرکز (۲ تا ۴) */
  related: string[];
  /** لینک به صفحه‌ی فرود/ابزارِ مرتبطِ آریون */
  cta?: { href: string; label: string };
};
