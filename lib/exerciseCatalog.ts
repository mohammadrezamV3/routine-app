// کاتالوگِ حرکات بدنسازی — برای بخشِ «مشاهده حرکات»: روی هر حرکتِ برنامه کلیک
// می‌شه و نحوه‌ی انجام، عضلاتِ درگیر و مزایاش نشون داده می‌شه. چون اسمِ هر
// حرکت توی lib/exercisePlans.ts همراهِ ست×تکرار/زمانه (مثلاً «اسکوات هالتر
// ۵×۵»)، اول با normalizeExerciseName یه اسمِ پایه استخراج می‌شه، بعد با
// کلیدهای این کاتالوگ مچ می‌شه. اگه چیزی دقیق پیدا نشد، fallback بر اساسِ
// خانواده‌ی حرکت (اسکوات/پرس/زیربغل/...) یه توضیحِ کلی می‌ده تا هیچ‌وقت خالی نمونه.

export type ExerciseCatalogEntry = {
  name: string;
  muscleGroup: string;
  howTo: string[];
  benefits: string;
};

const SET_REP_SUFFIX = /[\s]*[۰-۹0-9]+\s*[×xX]\s*[۰-۹0-9]+.*$/;
const TIME_SUFFIX = /[\s]*[۰-۹0-9]+\s*(دقیقه|ثانیه).*$/;
const PER_LIMB_SUFFIX = /\s*(هر\s*پا|هر\s*طرف)\s*$/;

/** «اسکوات هالتر ۵×۵» → «اسکوات هالتر» — اسمِ پایه‌ی حرکت بدونِ ست/تکرار/زمان */
export function normalizeExerciseName(item: string): string {
  return item
    .replace(PER_LIMB_SUFFIX, "")
    .replace(SET_REP_SUFFIX, "")
    .replace(TIME_SUFFIX, "")
    .trim();
}

